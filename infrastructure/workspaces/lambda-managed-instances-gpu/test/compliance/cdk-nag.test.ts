import * as cdk from 'aws-cdk-lib';
import { Annotations, Match } from 'aws-cdk-lib/assertions';
import { AwsSolutionsChecks, NagSuppressions } from 'cdk-nag';
import { buildStack, newApp, testParams } from '../helpers/stack';

const expectNoFindings = (stack: cdk.Stack): void => {
  const warnings = Annotations.fromStack(stack).findWarning('*', Match.stringLikeRegexp('AwsSolutions-.*'));
  const errors = Annotations.fromStack(stack).findError('*', Match.stringLikeRegexp('AwsSolutions-.*'));
  const findings = [...warnings, ...errors];
  if (findings.length > 0) {
    console.log(JSON.stringify(findings.map((f) => ({ id: f.id, entry: f.entry.data })), null, 2));
  }
  expect(findings).toHaveLength(0);
};

describe('CDK Nag AwsSolutions Pack', () => {
  test.each([
    ['Auto scaling', undefined],
    ['Manual GPU target tracking', 60],
  ])('stack (%s) has no unsuppressed findings', (_label, targetGpuUtilization) => {
    const app = newApp();
    const stack = buildStack(app, { capacity: { ...testParams().capacity, targetGpuUtilization } });
    applySuppressions(stack);
    cdk.Aspects.of(app).add(new AwsSolutionsChecks({ verbose: true }));
    app.synth();
    expectNoFindings(stack);
  });
});

/**
 * Suppressions. Each one is a CDK-managed helper or an AWS managed policy that
 * the service requires; the reason is recorded next to it.
 */
function applySuppressions(stack: cdk.Stack): void {
  const basicExecutionRole = 'Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole';

  NagSuppressions.addResourceSuppressionsByPath(
    stack,
    `/${stack.stackName}/GpuCapacityProvider/Resource/OperatorRole/Resource`,
    [
      {
        id: 'AwsSolutions-IAM4',
        reason:
          'AWSLambdaManagedEC2ResourceOperator is the AWS managed policy Lambda requires to launch and terminate the capacity provider instances; AWS keeps it in step with the service.',
        appliesTo: ['Policy::arn:<AWS::Partition>:iam::aws:policy/AWSLambdaManagedEC2ResourceOperator'],
      },
    ],
  );

  NagSuppressions.addResourceSuppressionsByPath(
    stack,
    `/${stack.stackName}/InferenceFunction/Resource/ServiceRole/Resource`,
    [
      {
        id: 'AwsSolutions-IAM4',
        reason: 'AWSLambdaBasicExecutionRole only grants CloudWatch Logs writes for the function log group.',
        appliesTo: [basicExecutionRole],
      },
    ],
  );

  NagSuppressions.addResourceSuppressionsByPath(
    stack,
    `/${stack.stackName}/InferenceFunction/Resource/ServiceRole/DefaultPolicy/Resource`,
    [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'Generated by bucket.grantRead(fn, "input/*"): read actions (s3:GetObject*, s3:GetBucket*, s3:List*) scoped to one bucket and the input/ prefix.',
        appliesTo: [
          'Action::s3:GetBucket*',
          'Action::s3:GetObject*',
          'Action::s3:List*',
          'Resource::<ImageBucket97210811.Arn>/input/*',
        ],
      },
    ],
  );

  NagSuppressions.addResourceSuppressionsByPath(
    stack,
    `/${stack.stackName}/BucketNotificationsHandler050a0587b7544547bf325f094a3db834/Role/Resource`,
    [
      {
        id: 'AwsSolutions-IAM4',
        reason: 'CDK-managed custom resource that configures the S3 event notification; not part of the workload.',
        appliesTo: [basicExecutionRole],
      },
    ],
  );

  NagSuppressions.addResourceSuppressionsByPath(stack, `/${stack.stackName}/Vpc/LogsEndpoint/SecurityGroup/Resource`, [
    {
      id: 'CdkNagValidationFailure',
      reason:
        'AwsSolutions-EC23 cannot evaluate the VPC CIDR token. The rule only allows HTTPS from the VPC CIDR (10.0.0.0/16), not 0.0.0.0/0.',
    },
  ]);
}
