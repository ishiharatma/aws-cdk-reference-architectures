import * as cdk from 'aws-cdk-lib';
import { Match, Template } from 'aws-cdk-lib/assertions';
import { LambdaWebFunctionsExpressStage } from 'lib/stages/lambda-web-functions-express-stage';
import { params } from 'parameters/environments';
import { buildL2Stack, envName, projectName, testEnv, webAclArn } from '../helpers/stack';

const FUNCTION_NAME = 'test-test-lwf2-todos';

describe('LambdaWebFunctionsExpressL2Stack (aws-cdk-lib 2.276.0 L2 constructs)', () => {
  let template: Template;

  beforeAll(() => {
    template = Template.fromStack(buildL2Stack());
  });

  describe('WebFunction', () => {
    test('one function, one revision and one endpoint, generated by lambda.WebFunction', () => {
      template.resourceCountIs('AWS::Lambda::WebFunction', 1);
      template.resourceCountIs('AWS::Lambda::WebFunctionRevision', 1);
      template.resourceCountIs('AWS::Lambda::WebFunctionEndpoint', 1);
      template.hasResourceProperties('AWS::Lambda::WebFunction', { FunctionName: FUNCTION_NAME });
    });

    test('revision runs nodejs24.x from the managed code bucket with the stack parameters', () => {
      template.hasResourceProperties('AWS::Lambda::WebFunctionRevision', {
        BuildConfig: {
          CodeConfig: {
            S3Object: {
              Bucket: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionCodeCopy'), 'Bucket'] },
              Key: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionCodeCopy'), 'Key'] },
              VersionId: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionCodeCopy'), 'VersionId'] },
            },
          },
          RuntimeConfig: { Runtime: 'nodejs24.x' },
        },
        ServiceConfig: {
          ExecutionRoleArn: { 'Fn::GetAtt': [Match.stringLikeRegexp('^ExecutionRole'), 'Arn'] },
          TimeoutSeconds: 30,
          MaxConcurrencyPerEnvironment: 64,
          EnvironmentVariables: {
            TABLE_NAME: { Ref: Match.stringLikeRegexp('TodosTable') },
            ENABLE_DEBUG_ROUTES: 'false',
          },
          TelemetryConfig: {
            LoggingConfig: {
              LogGroup: { Ref: Match.stringLikeRegexp('^LogGroup') },
              ApplicationLogLevel: 'INFO',
              SystemLogLevel: 'INFO',
            },
          },
        },
      });
    });

    test('revision waits for the `.local` log group and the execution role policy', () => {
      const revision = Object.values(template.findResources('AWS::Lambda::WebFunctionRevision'))[0];
      expect(revision.DependsOn).toEqual(
        expect.arrayContaining([
          expect.stringMatching(/^LocalLogGroup/),
          expect.stringMatching(/^ExecutionRoleDefaultPolicy/),
        ]),
      );
    });

    test('endpoint is IamAuth, HomeRegion, named after the environment, with scaling and throttle caps', () => {
      template.hasResourceProperties('AWS::Lambda::WebFunctionEndpoint', {
        EndpointName: envName,
        EndpointType: 'HomeRegion',
        AuthType: 'IamAuth',
        RevisionWeights: [
          { RevisionId: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionRevision'), 'RevisionId'] }, Weight: 100 },
        ],
        ScalingConfig: { MaxEnvironments: 3 },
        ThrottleConfig: { RateLimit: 100 },
      });
    });
  });

  describe('Code bucket (WebFunctionCode.fromAssetToManagedBucket)', () => {
    test('bucket is versioned, SSE-S3 encrypted and blocks public access', () => {
      template.hasResourceProperties('AWS::S3::Bucket', {
        VersioningConfiguration: { Status: 'Enabled' },
        BucketEncryption: {
          ServerSideEncryptionConfiguration: [{ ServerSideEncryptionByDefault: { SSEAlgorithm: 'AES256' } }],
        },
        PublicAccessBlockConfiguration: {
          BlockPublicAcls: true,
          BlockPublicPolicy: true,
          IgnorePublicAcls: true,
          RestrictPublicBuckets: true,
        },
      });
    });

    test('bucket policy lets lambda.amazonaws.com read the code', () => {
      template.hasResourceProperties('AWS::S3::BucketPolicy', {
        PolicyDocument: {
          Statement: Match.arrayWith([
            Match.objectLike({
              Principal: { Service: 'lambda.amazonaws.com' },
              Action: Match.arrayWith(['s3:GetObject', 's3:GetObjectVersion']),
            }),
          ]),
        },
      });
    });

    test('the copy function log group is owned by the stack with a retention', () => {
      template.hasResourceProperties('AWS::Logs::LogGroup', {
        LogGroupName: Match.absent(),
        RetentionInDays: 7,
      });
    });
  });

  describe('Logging and IAM', () => {
    test.each([`/aws/lambda/web/${FUNCTION_NAME}`, `/aws/lambda/web/${FUNCTION_NAME}.local`])(
      'log group %s has a retention',
      (logGroupName) => {
        template.hasResourceProperties('AWS::Logs::LogGroup', { LogGroupName: logGroupName, RetentionInDays: 7 });
      },
    );

    test('execution role does not use the L2 default AWSLambdaBasicExecutionRole', () => {
      const roles = template.findResources('AWS::IAM::Role', {
        Properties: { Description: Match.stringLikeRegexp('Lambda Web Function') },
      });
      expect(Object.keys(roles)).toHaveLength(1);
      expect(Object.values(roles)[0].Properties.ManagedPolicyArns).toBeUndefined();
    });

    test('execution role can write only to the function log groups', () => {
      template.hasResourceProperties('AWS::IAM::Policy', {
        PolicyDocument: {
          Statement: Match.arrayWith([
            Match.objectLike({
              Action: ['logs:CreateLogGroup', 'logs:CreateLogStream', 'logs:PutLogEvents'],
              Resource: [
                { 'Fn::Join': ['', Match.arrayWith([Match.stringLikeRegexp(`log-group:/aws/lambda/web/${FUNCTION_NAME}:\\*$`)])] },
                {
                  'Fn::Join': ['', Match.arrayWith([Match.stringLikeRegexp(`log-group:/aws/lambda/web/${FUNCTION_NAME}\\.local:\\*$`)])],
                },
              ],
            }),
          ]),
        },
      });
    });
  });

  describe('DynamoDB', () => {
    test('table name does not collide with the L1 stack', () => {
      template.hasResourceProperties('AWS::DynamoDB::Table', { TableName: 'test-test-lwf2-todos' });
    });
  });

  describe('CloudFront', () => {
    test('OAC is lambda / always-amz-auth / sigv4', () => {
      template.hasResourceProperties('AWS::CloudFront::OriginAccessControl', {
        OriginAccessControlConfig: Match.objectLike({
          Name: 'test-test-lwf2-web-function-oac',
          OriginAccessControlOriginType: 'lambda',
          SigningBehavior: 'always-amz-auth',
          SigningProtocol: 'sigv4',
        }),
      });
    });

    test('distribution targets the endpoint with the OAC and the WAF, without a property override', () => {
      template.hasResourceProperties('AWS::CloudFront::Distribution', {
        DistributionConfig: Match.objectLike({
          WebACLId: webAclArn,
          Origins: [
            Match.objectLike({
              DomainName: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionEndpoint'), 'DomainName'] },
              OriginAccessControlId: { 'Fn::GetAtt': [Match.stringLikeRegexp('WebFunctionOac'), 'Id'] },
              CustomOriginConfig: Match.objectLike({ OriginProtocolPolicy: 'https-only' }),
            }),
          ],
        }),
      });
    });

    test('endpoint.grants.invoke renders one resource policy for this distribution and endpoint', () => {
      template.resourceCountIs('AWS::Lambda::ResourcePolicy', 1);
      template.hasResourceProperties('AWS::Lambda::ResourcePolicy', {
        ResourceArn: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunction'), 'FunctionArn'] },
        PolicyDocument: {
          Statement: [
            Match.objectLike({
              Effect: 'Allow',
              Principal: { Service: 'cloudfront.amazonaws.com' },
              Action: 'lambda:InvokeWebFunctionEndpoint',
              Resource: { 'Fn::GetAtt': [Match.stringLikeRegexp('TodosWebFunctionEndpoint'), 'EndpointArn'] },
              Condition: { StringEquals: { 'aws:SourceArn': Match.anyValue() } },
            }),
          ],
        },
      });
    });
  });

  describe('Outputs', () => {
    test.each(['DistributionUrl', 'EndpointDomainName', 'WebFunctionName', 'RevisionId', 'LogGroupName'])(
      '%s is exported',
      (name) => {
        template.hasOutput(name, Match.anyValue());
      },
    );
  });
});

describe('LambdaWebFunctionsExpressL2Stack with VPC egress (NetworkConnector L2)', () => {
  const template = Template.fromStack(buildL2Stack(undefined, { vpcEgress: { enabled: true, maxAzs: 2 } }));

  test('no network connector unless enabled', () => {
    Template.fromStack(buildL2Stack()).resourceCountIs('AWS::Lambda::NetworkConnector', 0);
  });

  test('VPC_EGRESS connector for WebFunction in the isolated subnets', () => {
    template.hasResourceProperties('AWS::Lambda::NetworkConnector', {
      Name: 'test-test-lwf2-egress',
      OperatorRole: { 'Fn::GetAtt': [Match.stringLikeRegexp('EgressConnectorOperatorRole'), 'Arn'] },
      Configuration: {
        VpcEgressConfiguration: Match.objectLike({
          AssociatedComputeResourceTypes: ['WebFunction'],
          NetworkProtocol: 'IPv4',
          SubnetIds: Match.arrayWith([{ Ref: Match.stringLikeRegexp('VpcwebfunctionSubnet1') }]),
        }),
      },
    });
    template.resourceCountIs('AWS::EC2::NatGateway', 0);
  });

  test('default operator role carries AWSLambdaNetworkConnectorOperatorPolicy', () => {
    template.hasResourceProperties('AWS::IAM::Role', {
      ManagedPolicyArns: [
        { 'Fn::Join': ['', Match.arrayWith([Match.stringLikeRegexp('AWSLambdaNetworkConnectorOperatorPolicy$')])] },
      ],
    });
  });

  test('revision is pinned to LatestVersionArn without a property override', () => {
    template.hasResourceProperties('AWS::Lambda::WebFunctionRevision', {
      ServiceConfig: Match.objectLike({
        EgressNetworkConnectorArn: { 'Fn::GetAtt': [Match.stringLikeRegexp('EgressConnector'), 'LatestVersionArn'] },
      }),
    });
  });
});

describe('LambdaWebFunctionsExpressStage', () => {
  test('deploys the L1 and L2 stacks side by side, both after the WAF stack', () => {
    const envParams = params[envName];
    if (!envParams) {
      throw new Error(`No parameters found for environment: ${envName}`);
    }
    const app = new cdk.App({ context: { 'aws:cdk:bundling-stacks': [] } });
    const stage = new LambdaWebFunctionsExpressStage(app, 'Stage', {
      project: projectName,
      environment: envName,
      env: testEnv,
      terminationProtection: false,
      isAutoDeleteObject: true,
      params: envParams,
      allowedIps: ['203.0.113.10'],
    });
    const stacks = stage.node.children.filter((c): c is cdk.Stack => cdk.Stack.isStack(c));
    const names = stacks.map((s) => s.stackName);
    expect(names).toEqual(
      expect.arrayContaining([
        'test-test-lambda-web-functions-express',
        'test-test-lambda-web-functions-express-l2',
        'test-test-lambda-web-functions-express-waf',
      ]),
    );
    const waf = stacks.find((s) => s.stackName.endsWith('-waf'));
    expect(waf).toBeDefined();
    for (const stack of stacks.filter((s) => s !== waf)) {
      expect(stack.dependencies).toContain(waf);
    }
  });
});
