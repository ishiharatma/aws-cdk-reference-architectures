import * as cdk from 'aws-cdk-lib';
import { Annotations, Match } from 'aws-cdk-lib/assertions';
import { AwsSolutionsChecks, NagSuppressions } from 'cdk-nag';
import { buildStacks, newApp } from 'test/helpers/stack';

const expectNoFindings = (stack: cdk.Stack): void => {
  const warnings = Annotations.fromStack(stack).findWarning(
    '*',
    Match.stringLikeRegexp('AwsSolutions-.*')
  );
  const errors = Annotations.fromStack(stack).findError(
    '*',
    Match.stringLikeRegexp('AwsSolutions-.*')
  );
  const findings = [...warnings, ...errors];
  if (findings.length > 0) {
    console.log(
      JSON.stringify(
        findings.map((f) => ({ id: f.id, entry: f.entry.data })),
        null,
        2
      )
    );
  }
  expect(findings).toHaveLength(0);
};

describe('CDK Nag AwsSolutions Pack', () => {
  const app = newApp();
  const { data, application } = buildStacks({ app });
  applyDataSuppressions(data);
  applyApplicationSuppressions(application);
  cdk.Aspects.of(app).add(new AwsSolutionsChecks({ verbose: true }));
  app.synth();

  test('data stack has no unsuppressed findings', () => {
    expectNoFindings(data);
  });

  test('application stack has no unsuppressed findings', () => {
    expectNoFindings(application);
  });
});

/** Suppressions for the data stack; each one is documented in the README. */
function applyDataSuppressions(stack: cdk.Stack): void {
  NagSuppressions.addStackSuppressions(
    stack,
    [
      {
        id: 'AwsSolutions-S1',
        reason:
          "The report bucket is read and written only by this pipeline's roles (SSE-KMS, SSL only, no public access). " +
          'Object-level access auditing belongs to CloudTrail S3 data events, configured account-wide rather than per pattern.',
      },
      {
        id: 'AwsSolutions-SMG4',
        reason:
          'The secret holds Slack / Teams webhook URLs issued by those services; AWS cannot rotate them. ' +
          'They are replaced by hand when reissued.',
      },
    ],
    true
  );
}

